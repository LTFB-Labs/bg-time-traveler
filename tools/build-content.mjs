import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { parseCard, validateCard } from './lib/cards.mjs';
import { parseLesson, renderLesson, validateLesson } from './lib/lessons.mjs';
import { renderMarkdown } from './lib/markdown.mjs';
import { photoProblems } from './lib/photos.mjs';
import { formatProblems, problem } from './lib/problems.mjs';
import { buildSearchIndex } from './lib/search.mjs';
import { buildAliasIndex, linkTerms } from './lib/terms.mjs';

const HEADER = '/* generated by tools/build-content.mjs — do not edit; sources in content/ */';

export function buildContent(rootDir) {
    const dir = join(rootDir, 'content');
    const photos = readJson(dir, 'photos.json', {});
    const balkans = readJson(dir, 'maps/balkans.json', {});
    const cards = readCards(dir);
    const grades = readGrades(dir);
    const listed = Object.values(grades.rows).flat().filter((row) => row.lesson);
    const lessons = listed.map((row) => row.lesson);
    const ctx = { cards: new Map(cards.map((card) => [card.id, card])), borders: readBorderIds(join(dir, 'borders')), photos: new Set(Object.keys(photos.value)) };
    const aliases = buildAliasIndex(cards);
    const problems = [
        ...photos.problems,
        ...balkans.problems,
        ...grades.problems,
        ...cards.flatMap((card) => validateCard(card, ctx)),
        ...aliases.problems,
        ...listed.flatMap(idProblems),
        ...lessons.flatMap((lesson) => validateLesson(lesson, ctx)),
        ...photoProblems(referencedPhotos(cards, lessons), photos.value, readPhotoFiles(rootDir)),
    ];
    const content = {
        cards: toPageCards(cards, aliases.index),
        lessons: toPageLessons(lessons, aliases.index),
        grades: toPageGrades(grades.rows),
        photos: photos.value,
        maps: { balkans: balkans.value },
        search: [],
    };
    content.search = buildSearchIndex(content);
    return { content, problems };
}

export function renderContentJs(content) {
    const events = Object.values(content.cards).filter((card) => card.legacyKind).map(toEvent).sort((a, b) => a.y - b.y);
    return [
        HEADER,
        `const CONTENT = ${JSON.stringify(content)};`,
        `const EVENTS = ${JSON.stringify(events)};`,
        'const PHOTOS = CONTENT.photos;',
        'const { ERAS, RULERS, CITIES, MOUNTAINS, SEAS, CAMERA, START, END } = CONTENT.maps.balkans;',
        '',
    ].join('\n');
}

// Strips a byte order mark and turns Windows and old Mac line ends into \n, so every reader sees the same text.
function readText(file) {
    return readFileSync(file, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}

function readJson(dir, path, fallback) {
    try {
        return { value: JSON.parse(readText(join(dir, path))), problems: [] };
    } catch (error) {
        return { value: fallback, problems: [problem(path, error.code === 'ENOENT' ? 'file is missing' : `cannot read: ${error.message}`)] };
    }
}

function readCards(dir) {
    const cardsDir = join(dir, 'cards');
    return readdirSync(cardsDir).filter(isMarkdown).sort().map((name) => parseCard(readText(join(cardsDir, name)), `cards/${name}`));
}

function readGrades(dir) {
    const grades = readdirSync(join(dir, 'lessons'), { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => readGrade(dir, entry.name));
    return { rows: Object.fromEntries(grades.map(({ grade, rows }) => [grade, rows])), problems: grades.flatMap((grade) => grade.problems) };
}

function readGrade(dir, grade) {
    const folder = `lessons/${grade}`;
    const index = readJson(dir, `${folder}/index.json`, []);
    const rows = index.value.map((entry) => (entry.file ? { entry, lesson: readLesson(dir, `${folder}/${entry.file}`) } : { entry }));
    return { grade, rows, problems: [...index.problems, ...unlistedProblems(dir, folder, index.value)] };
}

function unlistedProblems(dir, folder, entries) {
    const listed = new Set(entries.map((entry) => entry.file));
    const unlisted = readdirSync(join(dir, folder)).filter((name) => isMarkdown(name) && !listed.has(name));
    return unlisted.map((name) => problem(`${folder}/${name}`, `not listed in ${folder}/index.json`));
}

function readLesson(dir, path) {
    return parseLesson(readText(join(dir, path)), path);
}

function isMarkdown(name) {
    return name.endsWith('.md');
}

function readBorderIds(bordersDir) {
    return new Set(readdirSync(bordersDir).filter((name) => name.endsWith('.geojson')).map((name) => basename(name, '.geojson')));
}

function readPhotoFiles(rootDir) {
    const photosDir = join(rootDir, 'photos');
    return new Set(existsSync(photosDir) ? readdirSync(photosDir).map((name) => `photos/${name}`) : []);
}

function referencedPhotos(cards, lessons) {
    const fromLessons = lessons.flatMap((lesson) => lesson.parts.map((part) => part.meta.photo));
    return [...new Set([...cards.map((card) => card.photo), ...fromLessons])].filter(Boolean);
}

function idProblems({ entry, lesson }) {
    return lesson.id === entry.id ? [] : [problem(lesson.file, `index.json lists id ${entry.id} but the front matter says ${lesson.id}`)];
}

function toPageCards(cards, aliasIndex) {
    return Object.fromEntries(cards.map((card) => [card.id, toPageCard(card, aliasIndex)]));
}

function toPageCard({ id, kind, legacyKind, title, dates, at, years, photo, aliases, paragraphs, path }, aliasIndex) {
    const html = paragraphs.map((paragraph) => linkTerms(renderMarkdown(paragraph), aliasIndex)).join('\n');
    return { id, kind, legacyKind, title, dates, at, years, photo, aliases, paragraphs, path, html };
}

function toPageLessons(lessons, aliasIndex) {
    return Object.fromEntries(lessons.map((lesson) => [lesson.id, toPageLesson(renderLesson(lesson, aliasIndex))]));
}

function toPageLesson({ file, parseError, parts, ...lesson }) {
    return { ...lesson, parts: parts.map(toPagePart) };
}

function toPagePart({ type, heading, meta, paragraphs, fact, html, factHtml }) {
    return { type, heading, meta, paragraphs, fact, html, factHtml };
}

function toPageGrades(grades) {
    return Object.fromEntries(Object.entries(grades).map(([grade, rows]) => [grade, rows.map(toGradeEntry)]));
}

function toGradeEntry({ entry, lesson }) {
    const { file, ...rest } = entry;
    return lesson ? { ...rest, title: lesson.title, number: lesson.number, span: lesson.span, map: lesson.map } : rest;
}

function toEvent(card) {
    const event = { id: card.id, y: card.years[0], kind: card.legacyKind, at: card.at, t: card.title, d: card.paragraphs[0] };
    return card.path ? { ...event, path: card.path } : event;
}

function rootFromArgs(args) {
    const flag = args.indexOf('--root');
    return flag >= 0 ? args[flag + 1] : join(import.meta.dirname, '..');
}

function main() {
    const root = rootFromArgs(process.argv.slice(2));
    const { content, problems } = buildContent(root);
    if (problems.length > 0) {
        console.error(formatProblems(problems));
        process.exit(1);
    }
    writeFileSync(join(root, 'content.js'), renderContentJs(content));
    console.log(`content.js written: ${Object.keys(content.cards).length} cards, ${Object.keys(content.lessons).length} lessons, ${content.search.length} search entries`);
}

if (import.meta.main) main();
